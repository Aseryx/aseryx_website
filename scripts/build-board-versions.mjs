// Writes src/data/boardVersions.js from the aseryx_benchmarks record: every published
// version's corpus marks and each board dataset's score in each version, from
// benchmarks/reports/evolution/evolution.json.
//
// Usage: node scripts/build-board-versions.mjs [path to aseryx_benchmarks]
// (default ../aseryx_benchmarks, or ASERYX_BENCHMARKS). It fails without writing
// when a board row has no single matching file in the record, or when the
// record's v11 scores or marks differ from what readinessBoard.js publishes.
import { readFileSync, writeFileSync } from 'fs';
import { dirname, resolve } from 'path';
import { fileURLToPath } from 'url';
import BOARD_ROWS, { BOARD_MARKS } from '../src/data/readinessBoard.js';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const benchmarks = resolve(root, process.argv[2] ?? process.env.ASERYX_BENCHMARKS ?? '../aseryx_benchmarks');
const recordPath = 'benchmarks/reports/evolution/evolution.json';
const outPath = resolve(root, 'src/data/boardVersions.js');

// The public versions, oldest first. Only major versions are published: v10 is
// rules v10.2, the last rules shipped as v10. v7 to v9 were development steps.
const PUBLISHED = [
  { version: 'v6', from: 'v6', shipped: true, status: 'retired', note: 'in the product until 2026-10-23' },
  { version: 'v7', from: 'v7', shipped: false, status: 'never shipped', note: 'development step, superseded 2026-10-22' },
  { version: 'v8', from: 'v8', shipped: false, status: 'never shipped', note: 'development step, superseded 2026-10-22' },
  { version: 'v9', from: 'v9', shipped: false, status: 'never shipped', note: 'development step, frozen 2026-10-23' },
  { version: 'v10', from: 'v10.2', shipped: true, status: 'retired', note: 'in the product from 2026-10-23 to 2026-10-30' },
  { version: 'v11', from: 'v11', shipped: true, status: 'live now', note: 'in the product since 2026-10-30' },
];
const MARKS = ['good90', 'good', 'dirty70', 'dirty', 'goodAboveDirtyPct', 'rankCorrelation', 'pairsInOrder', 'pairs'];

const fail = (problems) => {
  console.error(`build-board-versions: nothing written.\n${problems.map((p) => `  ${p}`).join('\n')}`);
  process.exit(1);
};

const readRecord = () => {
  try {
    return JSON.parse(readFileSync(resolve(benchmarks, recordPath), 'utf8'));
  } catch (error) {
    return fail([`cannot read ${resolve(benchmarks, recordPath)}: ${error.message}`]);
  }
};
const record = readRecord();
const recordVersions = new Map(record.versions.map((v) => [v.version, v]));
const problems = [];

const versions = PUBLISHED.map((p) => {
  const v = recordVersions.get(p.from);
  if (!v) {
    problems.push(`${recordPath} has no version ${p.from}`);
    return null;
  }
  const marks = Object.fromEntries(MARKS.map((m) => [m, v[m]]));
  const missing = MARKS.filter((m) => typeof marks[m] !== 'number');
  if (missing.length) problems.push(`${p.from} lacks ${missing.join(', ')}`);
  return { version: p.version, shipped: p.shipped, status: p.status, note: p.note, ...marks };
});

const latest = recordVersions.get(PUBLISHED[PUBLISHED.length - 1].from);
for (const [mark, value] of Object.entries(BOARD_MARKS)) {
  if (latest && latest[mark] !== value) problems.push(`BOARD_MARKS.${mark} is ${value}, the record says ${latest[mark]}`);
}

const filesByDataset = new Map();
for (const f of record.files) filesByDataset.set(f.dataset, [...(filesByDataset.get(f.dataset) ?? []), f]);

const history = BOARD_ROWS.map((row) => {
  const files = filesByDataset.get(row.key) ?? [];
  if (files.length !== 1) {
    problems.push(`${row.key}: ${files.length} files in the record, expected 1`);
    return null;
  }
  const { scores, file } = files[0];
  const latestScore = scores[PUBLISHED[PUBLISHED.length - 1].from];
  if (row.score != null && latestScore !== row.score) problems.push(`${row.key}: board score ${row.score}, ${file} scores ${latestScore}`);
  const series = PUBLISHED.map((p) => scores[p.from]);
  if (series.some((s) => typeof s !== 'number')) problems.push(`${row.key}: ${file} lacks a score in a published version`);
  return [row.key, series];
});

if (problems.length) fail(problems);

const json = (value) =>
  JSON.stringify(value)
    .replace(/"(\w+)":/g, '$1: ')
    .replace(/"([^"]*)"/g, "'$1'")
    .replace(/,(?=\S)/g, ', ')
    .replace(/^\{/, '{ ')
    .replace(/\}$/, ' }');
const out = `// Generated by scripts/build-board-versions.mjs from aseryx_benchmarks ${recordPath}.
// Run it again after the record changes; do not edit by hand.

/**
 * Every published version of the score, oldest first, with its marks on the
 * corpus: good90 of good known-good files at 90 or more, dirty70 of dirty
 * known-dirty files under 70, the share of good-and-dirty pairs in order, the
 * rank correlation, and pairsInOrder of pairs clean and dirty twins in order.
 */
export const BOARD_VERSIONS = [
${versions.map((v) => `  ${json(v)},`).join('\n')}
];

/** Each board dataset's score in every version of BOARD_VERSIONS, in the same order. */
export const BOARD_HISTORY = {
${history.map(([key, series]) => `  ${/^[A-Za-z_$][\w$]*$/.test(key) ? key : `'${key}'`}: ${json(series)},`).join('\n')}
};
`;
writeFileSync(outPath, out);
console.log(`build-board-versions: ${versions.length} versions, ${history.length} datasets written to src/data/boardVersions.js`);
